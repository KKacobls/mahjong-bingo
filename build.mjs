import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const dist = path.join(root, 'dist');
const output = path.join(root, 'docs');
await mkdir(output, {recursive:true});
const [html,css,math,shuffle,records,live,app,worker] = await Promise.all(['index.html','style.css','math.mjs','shuffle.mjs','records.mjs','live.mjs','app.mjs','worker.mjs'].map(name=>readFile(path.join(dist,name),'utf8')));
const stripImports = source => source.replace(/^import .*;\r?\n/gm,'');
const mathInline = math.replace(/^export /gm,'');
const shuffleInline = shuffle.replace(/^export /gm,'');
const recordsInline = records.replace(/^export /gm,'');
const liveInline = live.replace(/^export /gm,'');
const workerInline = `${mathInline}\n${stripImports(worker)}`;
const tileFiles = [...['Man','Pin','Sou'].flatMap(suit=>Array.from({length:9},(_,i)=>`${suit}${i+1}.png`)),...['Ton','Nan','Shaa','Pei','Haku','Hatsu','Chun','Man5-Dora','Sou5-Dora'].map(name=>`${name}.png`)];
const assets = Object.fromEntries(await Promise.all(tileFiles.map(async name=>[`tiles/${name}`,`data:image/png;base64,${(await readFile(path.join(dist,'assets/tiles',name))).toString('base64')}`])));
const appInline = stripImports(app).replace('element.src = `assets/${images[id]}`;','element.src = offlineAssets[images[id]];').replace("new Worker(new URL('./worker.mjs', import.meta.url), { type: 'module' })",'new Worker(offlineWorkerUrl)');
const script = `const offlineAssets=${JSON.stringify(assets)};\nconst offlineWorkerUrl=URL.createObjectURL(new Blob([${JSON.stringify(workerInline)}],{type:'text/javascript'}));\n${mathInline}\n${shuffleInline}\n${recordsInline}\n${liveInline}\n${appInline}`;
const standalone = html.replace('<link rel="stylesheet" href="style.css">',`<style>${css}</style>`).replace('<script type="module" src="app.mjs"></script>',`<script type="module">${script.replaceAll('</script','<\\/script')}</script>`);
await writeFile(path.join(output,'index.html'),standalone);
await writeFile(path.join(root,'index.html'),standalone);
await writeFile(path.join(output,'.nojekyll'),'');
console.log('Built index.html and docs/index.html');
